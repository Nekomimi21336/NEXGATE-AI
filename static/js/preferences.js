const THEME_TRANSITION_MS = 300;

function prefersReducedMotion() {
  return window.matchMedia("(prefers-reduced-motion: reduce)").matches;
}

function applyTheme(theme, options) {
  const animate = options && options.animate === true;
  const allowed = ["dark", "light", "system", "midnight"];
  const t = allowed.includes(theme) ? theme : "dark";
  const root = document.documentElement;

  const commit = () => {
    root.setAttribute("data-theme", t);
    try {
      localStorage.setItem("nexgate_theme", t);
    } catch (e) {}
  };

  if (!animate || prefersReducedMotion()) {
    commit();
    return;
  }

  if (typeof document.startViewTransition === "function") {
    document.startViewTransition(commit);
    return;
  }

  root.classList.add("theme-transition");
  commit();
  window.setTimeout(() => root.classList.remove("theme-transition"), THEME_TRANSITION_MS);
}

function applyChatBackground(pattern) {
  const allowed = ["simple", "grid"];
  const value = allowed.includes(pattern) ? pattern : "simple";
  document.documentElement.setAttribute("data-chat-background", value);
  try {
    localStorage.setItem("nexgate_chat_background", value);
  } catch (e) {}
}

function applyLanguage(lang, root) {
  const dict = I18N[lang] || I18N.ja;
  const htmlLang = lang === "en" ? "en" : lang === "ko" ? "ko" : "ja";
  document.documentElement.lang = htmlLang;

  const scope = root && typeof root.querySelectorAll === "function" ? root : document;

  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });

  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.placeholder = dict[key];
  });

  scope.querySelectorAll("[data-i18n-opt]").forEach((el) => {
    const key = el.dataset.i18nOpt;
    if (dict[key]) el.textContent = dict[key];
  });

  scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria;
    if (dict[key]) el.setAttribute("aria-label", dict[key]);
  });

  window.chatToolsBar?.refresh?.();
  window.updateChatInputIndicators?.();
  window.customAgentSelect?.refresh?.();
  window.refreshTableExportLabels?.(scope);
}

function initPreferences(user) {
  if (!user) return;
  applyTheme(user.theme || "dark");
  applyChatBackground(user.chat_background_pattern || "simple");
  const lang = user.language || "ja";
  const roots = [
    document.querySelector(".sidebar-region"),
    document.querySelector(".app-view.is-active"),
    document.querySelector(".nexcore-brand"),
  ].filter(Boolean);
  if (!roots.length) {
    applyLanguage(lang);
    return;
  }
  roots.forEach((root) => applyLanguage(lang, root));
}

if (window.__USER__) {
  initPreferences(window.__USER__);
}

window.applyTheme = applyTheme;
window.applyChatBackground = applyChatBackground;
window.applyLanguage = applyLanguage;
window.initPreferences = initPreferences;
window.t = (key) => (I18N[window.__USER__?.language || "ja"] || I18N.ja)[key] || key;
